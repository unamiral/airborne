/**
 * Generates docs/signal-report.md from the synthetic suite.
 * Run: npm run report:signal
 */
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { SEED_STABILIZER_PRESETS, STABILIZER_PRESETS, type OneEuroParams } from '../../src/app/config';
import { corners, filterSamples, moving, stationaryNoise, zigzag } from '../support/signal-eval';
import { bestLag, circle, line, percentileOf, polyline, sample, shapeErrors, sine, vertexDisplacement, type Path } from '../support/synthetic';

const heldOut = (): Path[] => [
  line(250, 30),
  line(600, -60, 1500),
  circle(35, 1400),
  circle(80, 3000),
  sine(25, 150, 180),
  zigzag(),
  polyline('loop', [{ x: 500, y: 300 }, { x: 600, y: 260 }, { x: 650, y: 330 }, { x: 560, y: 380 }, { x: 520, y: 320 }, { x: 700, y: 300 }], 280),
];

function fmt(p: OneEuroParams): string {
  return `min ${p.minCutoffHz} Hz, β ${p.beta}, d ${p.derivativeCutoffHz} Hz`;
}

it('writes docs/signal-report.md', () => {
  const sets: Array<[string, Record<string, OneEuroParams>]> = [
    ['Plan seeds', SEED_STABILIZER_PRESETS],
    ['Tuned (shipped)', STABILIZER_PRESETS],
  ];
  const lines: string[] = [
    '# Pen stabilizer signal report',
    '',
    'Generated by `npm run report:signal` from seeded synthetic traces (tests/support/synthetic.ts).',
    'Synthetic ground truth only: no real-camera traces and no user trials are included here.',
    'Noise is independent Gaussian per axis with the stated σ in surface CSS px; sampling has ±5% timing jitter.',
    'Lag is the best global time shift against ground truth; shape error is measured after removing that lag,',
    'excluding the first 150 ms; vertex displacement is the distance from a true vertex to the filtered polyline.',
    '',
  ];
  for (const [title, presets] of sets) {
    lines.push(`## ${title}`, '');
    for (const [name, p] of Object.entries(presets)) lines.push(`- ${name}: ${fmt(p)}`);
    lines.push('', '### Stationary radial RMS reduction (after 0.5 s)', '', '| Preset | Rate | σ=1 px | σ=2 px | σ=4 px |', '|---|---:|---:|---:|---:|');
    for (const [name, p] of Object.entries(presets)) {
      for (const rate of [15, 30, 60]) {
        const r = [1, 2, 4].map((n) => `${(stationaryNoise(p, n, rate).reduction * 100).toFixed(0)}%`);
        lines.push(`| ${name} | ${rate} Hz | ${r.join(' | ')} |`);
      }
    }
    lines.push('', '### Moving traces at 30 Hz: lag (ms) / p95 shape error (px)', '');
    const names = moving(presets.balanced!, 30, 1).map((m) => `${m.name} (${m.speed} px/s)`);
    lines.push(`| Preset | σ | ${names.join(' | ')} | median lag |`, `|---|---:|${names.map(() => '---:').join('|')}|---:|`);
    for (const [name, p] of Object.entries(presets)) {
      for (const noise of [1, 2]) {
        const mv = moving(p, 30, noise);
        const lags = mv.map((m) => m.lagMs).sort((a, b) => a - b);
        lines.push(`| ${name} | ${noise} | ${mv.map((m) => `${m.lagMs} / ${m.p95ShapeErrorPx.toFixed(2)}`).join(' | ')} | ${lags[Math.floor(lags.length / 2)]} |`);
      }
    }
    lines.push('', '### Corner vertex displacement (px), 45° / 90° / 135° interior angle', '', '| Preset | Rate | σ=1 px | σ=2 px |', '|---|---:|---|---|');
    for (const [name, p] of Object.entries(presets)) {
      for (const rate of [15, 30, 60]) {
        const c = [1, 2].map((n) => corners(p, rate, n).map((x) => x.vertexDisplacementPx.toFixed(1)).join(' / '));
        lines.push(`| ${name} | ${rate} Hz | ${c.join(' | ')} |`);
      }
    }
    lines.push('', '### Held-out traces (not used for tuning), Balanced, 30 Hz', '', '| Trace | σ | lag ms | p95 shape px | vertex px |', '|---|---:|---:|---:|---:|');
    for (const noise of [1, 2]) {
      heldOut().forEach((path, i) => {
        const { observed } = sample(path, { rateHz: 30, noisePx: noise, seed: 1000 + i, jitter: 0.1 });
        const out = filterSamples(observed, presets.balanced!);
        const lag = bestLag(out, path);
        const p95 = percentileOf(shapeErrors(out, path, lag, 150), 95);
        const v = path.vertices !== undefined && path.vertices.length > 0 ? Math.max(...vertexDisplacement(out, path)).toFixed(2) : '–';
        lines.push(`| ${path.name} | ${noise} | ${lag} | ${p95.toFixed(2)} | ${v} |`);
      });
    }
    lines.push('');
  }
  const b = STABILIZER_PRESETS.balanced;
  const st = stationaryNoise(b, 2, 30).reduction;
  const mv2 = moving(b, 30, 2);
  const mv1 = moving(b, 30, 1);
  const medLag = mv2.map((m) => m.lagMs).sort((x, y) => x - y)[3]!;
  const shapeMax = Math.max(...mv1.map((m) => m.p95ShapeErrorPx));
  const shapeMax2 = Math.max(...mv2.map((m) => m.p95ShapeErrorPx));
  const cornerMax = Math.max(...corners(b, 30, 1).map((c) => c.vertexDisplacementPx));
  const pass = (ok: boolean): string => (ok ? 'pass' : '**fail**');
  lines.push(
    '## Gate summary (shipped Balanced, 30 Hz)',
    '',
    '| Gate | Target | Result | Status |',
    '|---|---|---|---|',
    `| Stationary noise (σ=2 px) | ≥ 50% RMS reduction | ${(st * 100).toFixed(0)}% | ${pass(st >= 0.5)} |`,
    `| Median added lag, moving traces (σ=2 px) | ≤ 25 ms | ${medLag} ms | ${pass(medLag <= 25)} |`,
    `| p95 shape error after lag, standard paths (σ=1 px) | ≤ 3 px | max ${shapeMax.toFixed(2)} px | ${pass(shapeMax <= 3)} |`,
    `| Same at σ=2 px | ≤ 3 px | max ${shapeMax2.toFixed(2)} px | ${pass(shapeMax2 <= 3)} |`,
    `| Standard corners (σ=1 px) | ≤ 4 px | max ${cornerMax.toFixed(2)} px | ${pass(cornerMax <= 4)} |`,
    '| Held-out zigzag / loop vertices (σ=1 px) | ≤ 4 px | see table | **fail** (sharp short segments) |',
    '| 15 Hz sampling corners | ≤ 4 px | see table | **fail** (sparse samples) |',
    '',
    'At σ=2 px the raw p95 error is already 4.5–5.1 px, so filtering alone cannot reach 3 px without more lag;',
    'this tradeoff is reported rather than hidden. Real-camera noise levels have not been measured yet.',
    '',
  );
  writeFileSync('docs/signal-report.md', `${lines.join('\n')}\n`);
});
